    assert.equal(fixture('inspect').port, 2525); assert.equal(fixture('inspect').tested, false);
    record('Success followed by a real authentication failure cannot reuse old evidence when the user explicitly saves');
    phase = 'explicit matching save can apply successful current test';
    await field('port').fill('2465'); await field('encryption').selectOption('tls'); await field('password').fill(password);
    await test(true, 'current_unsaved');
    assert.equal((await save()).status(), 303);
    await page.waitForURL('**/admin/settings/mail');
    assert.equal(fixture('inspect').port, 2465); assert.equal(fixture('inspect').tested, true);
    record('Only the explicit matching Save applies successful current-connection evidence; Save sends no message');
    phase = 'save validation failure and secret handling';
    await field('sender_name').fill('Retained sender after save error'); await field('sender_address').fill('invalid-address');
    await field('password').fill(password);
    await form.evaluate(node => { node.noValidate = true; });
    assert.equal((await save()).status(), 422);
    await page.waitForURL('**/admin/settings/mail/update');
